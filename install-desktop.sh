#!/usr/bin/env bash
# ==============================================================================
# NixManager Pro — Bulletproof Desktop Integration Installer
# Installs CLI wrapper in ~/.local/bin and .desktop launcher in ~/.local/share/applications
# ==============================================================================

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BIN_DIR="${HOME}/.local/bin"
DESKTOP_DIR="${HOME}/.local/share/applications"
ICON_DIR="${HOME}/.local/share/icons/hicolor/scalable/apps"

mkdir -p "${BIN_DIR}" "${DESKTOP_DIR}" "${ICON_DIR}"

echo "❄️  Installing NixManager Pro Desktop Integration..."

# 1. Detect Python virtual environment or system Python
if [ -f "${SCRIPT_DIR}/.venv/bin/python3" ]; then
    PYTHON_BIN="${SCRIPT_DIR}/.venv/bin/python3"
elif [ -f "${SCRIPT_DIR}/.venv/bin/python" ]; then
    PYTHON_BIN="${SCRIPT_DIR}/.venv/bin/python"
else
    PYTHON_BIN="$(which python3)"
fi

WRAPPER_BIN="${BIN_DIR}/nixmanager"
cat << EOF > "${WRAPPER_BIN}"
#!/usr/bin/env bash
# Autogenerated launcher wrapper by NixManager Pro
if [ -e "\$HOME/.nix-profile/etc/profile.d/nix.sh" ]; then
    . "\$HOME/.nix-profile/etc/profile.d/nix.sh"
elif [ -e "/nix/var/nix/profiles/default/etc/profile.d/nix.sh" ]; then
    . "/nix/var/nix/profiles/default/etc/profile.d/nix.sh"
fi
export PATH="\$HOME/.nix-profile/bin:/nix/var/nix/profiles/default/bin:\$PATH"
export XDG_DATA_DIRS="\$HOME/.nix-profile/share:/nix/var/nix/profiles/default/share:\${XDG_DATA_DIRS:-/usr/local/share:/usr/share}"

cd "${SCRIPT_DIR}" || exit 1
exec "${PYTHON_BIN}" "${SCRIPT_DIR}/main.py" "\$@"
EOF
chmod +x "${WRAPPER_BIN}"

# 2. Install desktop icons (SVG and high-res PNG for all desktop themes)
if [ -f "${SCRIPT_DIR}/assets/nixmanager.svg" ]; then
    cp -f "${SCRIPT_DIR}/assets/nixmanager.svg" "${ICON_DIR}/nixmanager.svg"
fi
if [ -f "${SCRIPT_DIR}/assets/nixmanager.png" ]; then
    mkdir -p "${HOME}/.local/share/icons/hicolor/128x128/apps"
    cp -f "${SCRIPT_DIR}/assets/nixmanager.png" "${HOME}/.local/share/icons/hicolor/128x128/apps/nixmanager.png"
    mkdir -p "${HOME}/.local/share/icons/hicolor/256x256/apps"
    cp -f "${SCRIPT_DIR}/assets/nixmanager.png" "${HOME}/.local/share/icons/hicolor/256x256/apps/nixmanager.png"
    mkdir -p "${HOME}/.local/share/pixmaps"
    cp -f "${SCRIPT_DIR}/assets/nixmanager.png" "${HOME}/.local/share/pixmaps/nixmanager.png"
fi

# 3. Create .desktop file
DESKTOP_FILE="${DESKTOP_DIR}/nixmanager.desktop"
cat << EOF > "${DESKTOP_FILE}"
[Desktop Entry]
Version=1.0
Type=Application
Name=NixManager Pro
GenericName=Nix Package Manager
Comment=Desktop package manager and system control center for Nix
Exec=${WRAPPER_BIN}
Icon=nixmanager
Terminal=false
Categories=System;PackageManager;Settings;
Keywords=nix;nixos;package;manager;store;software;
StartupNotify=true
StartupWMClass=nixmanager
EOF
chmod +x "${DESKTOP_FILE}"

# 4. Refresh Desktop database
if command -v update-desktop-database >/dev/null 2>&1; then
    update-desktop-database "${DESKTOP_DIR}" || true
fi

echo "✅ Desktop launcher installed to: ${DESKTOP_FILE}"
echo "✅ Terminal shortcut installed to: ${WRAPPER_BIN}"
echo "🎉 You can now launch NixManager Pro from your Ubuntu App Grid or by typing 'nixmanager' in any terminal!"
